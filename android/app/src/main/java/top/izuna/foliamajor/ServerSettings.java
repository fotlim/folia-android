package top.izuna.foliamajor;

import android.app.Activity;
import android.app.AlertDialog;
import android.content.Context;
import android.content.SharedPreferences;
import android.text.InputType;
import android.view.ViewGroup;
import android.widget.EditText;
import android.widget.LinearLayout;
import android.widget.TextView;

import org.json.JSONObject;

// android/app/src/main/java/top/izuna/foliamajor/ServerSettings.java
// The online-music backends are separate deployments the user hosts, and the APK cannot ask the
// build for their address. They are kept in SharedPreferences and handed to the web app as
// runtime-config.js, which the asset handler generates per request, so a change takes effect on the
// next reload without rebuilding anything.
final class ServerSettings {

    private static final String PREFS = "folia_servers";
    private static final String KEY_NETEASE = "netease";
    private static final String KEY_KUGOU = "kugou";
    private static final String KEY_QQ = "qq";
    private static final String KEY_NOTIFICATIONS_ASKED = "notifications_asked";

    private ServerSettings() {
    }

    private static SharedPreferences prefs(Context context) {
        return context.getApplicationContext().getSharedPreferences(PREFS, Context.MODE_PRIVATE);
    }

    static String netease(Context context) {
        return prefs(context).getString(KEY_NETEASE, "");
    }

    static String kugou(Context context) {
        return prefs(context).getString(KEY_KUGOU, "");
    }

    static String qq(Context context) {
        return prefs(context).getString(KEY_QQ, "");
    }

    /** Persists what runtime discovery found, so the next boot starts from the same addresses. */
    static void save(Context context, String netease, String kugou, String qq) {
        prefs(context).edit()
                .putString(KEY_NETEASE, netease == null ? "" : netease.trim())
                .putString(KEY_KUGOU, kugou == null ? "" : kugou.trim())
                .putString(KEY_QQ, qq == null ? "" : qq.trim())
                .apply();
    }


    /** Whether the notification permission has already been asked for; it is asked at most once. */
    static boolean wasNotificationPermissionAsked(Context context) {
        return prefs(context).getBoolean(KEY_NOTIFICATIONS_ASKED, false);
    }

    static void markNotificationPermissionAsked(Context context) {
        prefs(context).edit().putBoolean(KEY_NOTIFICATIONS_ASKED, true).apply();
    }

    private static void putIfNotEmpty(JSONObject target, String key, String value) {
        if (value == null) return;
        String trimmed = value.trim();
        if (trimmed.isEmpty()) return;
        try {
            target.put(key, trimmed);
        } catch (Exception ignored) {
            // A missing field simply leaves that provider unconfigured.
        }
    }

    /** The script the app loads before its own bundle; same shape Docker writes. */
    static String buildRuntimeConfigJs(Context context) {
        JSONObject servers = new JSONObject();
        putIfNotEmpty(servers, "netease", netease(context));
        putIfNotEmpty(servers, "kugou", kugou(context));
        putIfNotEmpty(servers, "qq", qq(context));

        return "// Generated by the Android shell from the device's own settings.\n"
                + "window.__FOLIA_RUNTIME_CONFIG__ = window.__FOLIA_RUNTIME_CONFIG__ || {};\n"
                + "window.__FOLIA_RUNTIME_CONFIG__.shell = 'android';\n"
                + "window.__FOLIA_RUNTIME_CONFIG__.servers = " + servers + ";\n";
    }

    private static EditText field(Context context, String label, String value, String hint) {
        EditText input = new EditText(context);
        input.setHint(hint);
        input.setText(value);
        input.setTextSize(14);
        input.setSingleLine(true);
        input.setInputType(InputType.TYPE_CLASS_TEXT | InputType.TYPE_TEXT_VARIATION_URI);
        input.setContentDescription(label);
        LinearLayout.LayoutParams params = new LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT);
        params.topMargin = 12;
        input.setLayoutParams(params);
        return input;
    }

    private static TextView caption(Context context, String text) {
        TextView view = new TextView(context);
        view.setText(text);
        view.setTextSize(12);
        view.setAlpha(0.7f);
        view.setLayoutParams(new LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.WRAP_CONTENT));
        return view;
    }

    /**
     * A native dialog rather than a web settings page: the addresses have to be known before the web
     * app boots, and they are the one setting that must survive a broken bundle.
     */
    static void showDialog(Activity activity) {
        LinearLayout container = new LinearLayout(activity);
        container.setOrientation(LinearLayout.VERTICAL);
        int padding = Math.round(20 * activity.getResources().getDisplayMetrics().density);
        container.setPadding(padding, padding / 2, padding, 0);

        container.addView(caption(activity, "NeteaseCloudMusicApiEnhanced"));
        EditText netease = field(activity, "netease", netease(activity), "http://192.168.1.10:3000");
        container.addView(netease);

        container.addView(caption(activity, "KuGouMusicApi"));
        EditText kugou = field(activity, "kugou", kugou(activity), "http://192.168.1.10:3400");
        container.addView(kugou);

        container.addView(caption(activity, "qq-music-api"));
        EditText qq = field(activity, "qq", qq(activity), "http://192.168.1.10:3200");
        container.addView(qq);

        container.addView(caption(activity, "Leave a field empty to disable that provider. The app reloads after saving."));

        new AlertDialog.Builder(activity)
                .setTitle("Server endpoints")
                .setView(container)
                .setPositiveButton("Save", (dialog, which) -> {
                    prefs(activity).edit()
                            .putString(KEY_NETEASE, netease.getText().toString().trim())
                            .putString(KEY_KUGOU, kugou.getText().toString().trim())
                            .putString(KEY_QQ, qq.getText().toString().trim())
                            .apply();
                    if (activity instanceof MainActivity) {
                        ((MainActivity) activity).reloadWebApp();
                    }
                })
                .setNegativeButton("Cancel", null)
                .show();
    }
}
